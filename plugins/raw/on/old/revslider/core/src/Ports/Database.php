if(!defined('ABSPATH')) exit();

/**
 * The host's database behind one port: plain CRUD on the plugin's own tables.
 * Semantics mirror wpdb 1:1 so the ~150 existing call sites convert mechanically;
 * $output values are the strings 'OBJECT', 'ARRAY_A', 'ARRAY_N' (identical to the
 * WP constants of the same name).
 * @since 7.2.1
 */
interface Database {

	/** @return string table name prefix of the host's database */
	public function prefix();

	/**
	 * placeholder substitution identical to wpdb::prepare (%s, %d, %f, %i)
	 * @param string $query
	 * @return string|null
	 */
	public function prepare($query, ...$args);

	/**
	 * @param string $query
	 * @param string $output
	 * @return array|object|null
	 */
	public function get_row($query, $output = 'OBJECT');

	/**
	 * @param string $query
	 * @param string $output
	 * @return array
	 */
	public function get_results($query, $output = 'OBJECT');

	/**
	 * @param string $query
	 * @return string|null a single value
	 */
	public function get_var($query);

	/**
	 * @param string $table full table name including prefix
	 * @param array  $data  column => value
	 * @return int|false rows inserted or false on error
	 */
	public function insert($table, $data, $format = null);

	/** @return int id generated by the most recent insert */
	public function insert_id();

	/**
	 * @param string $table full table name including prefix
	 * @param array  $data  column => value
	 * @param array  $where column => value, joined with AND
	 * @return int|false rows updated or false on error
	 */
	public function update($table, $data, $where, $format = null, $where_format = null);

	/**
	 * @param string $table full table name including prefix
	 * @param array  $where column => value, joined with AND
	 * @return int|false rows deleted or false on error
	 */
	public function delete($table, $where, $where_format = null);

	/**
	 * run a raw statement
	 * @param string $query
	 * @return int|bool affected rows, true for CREATE-like statements, false on error
	 */
	public function query($query);

	/**
	 * @param string $text
	 * @return string escaped for use inside a LIKE expression (still needs prepare)
	 */
	public function esc_like($text);

	/** @return string error text of the most recent statement, '' when it succeeded */
	public function last_error();

	/** @return string the charset/collation clause a new table is created with, '' when the host sets none */
	public function charset_collate();

	/**
	 * bring one table to a CREATE TABLE definition: create it when missing, add missing columns and indexes, never drop
	 * @param string $sql one CREATE TABLE statement (Core\Schema writes them in the layout dbDelta parses)
	 * @return array what the host changed, one message per change
	 */
	public function sync_table($sql);
}
